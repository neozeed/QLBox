#!/usr/bin/env python3
"""Refresh observation-only hook addresses after rebuilding the bundled ROM."""
from pathlib import Path
root=Path(__file__).resolve().parent.parent
symbols={fields[2]:int(fields[0],16) for line in
 (root/'rom/qlbox-rom/build/qlbox.symbols').read_text().splitlines()
 if len(fields:=line.split())==3}
required={'QL_PC_BOOT_WAIT':'getmod','QL_PC_BASIC_READY':'l04c04',
          'QL_PC_KEY_DECODED':'l02eec','QL_PC_RAM_ERROR':'l0015c'}
text='/* Generated by tools/rom-symbols.py; observation only, no ROM patch. */\n'
for name,symbol in required.items():text+=f'#define {name} 0x{symbols[symbol]:06x}u\n'
(root/'src/rom_symbols.h').write_text(text)

#!/usr/bin/env python3
"""Regenerate embedded read-only utility drive; no host runtime files needed."""
from pathlib import Path
root=Path(__file__).resolve().parent.parent
out=['/* Generated by tools/embed-utils.py. */','typedef struct {const char *name; const unsigned char *data; unsigned size,type,dataspace;} BuiltinFile;']
files=['README_TXT','TK2_BAS','TK2_BIN','UNZIP','ZIP','EXIT']
for i,n in enumerate(files):
 d=(root/'util'/n).read_bytes()
 out.append('static const unsigned char builtin_%d[] = {'%i)
 out.extend(','.join(str(x) for x in d[j:j+24])+',' for j in range(0,len(d),24))
 out.append('};')
out.append('static const BuiltinFile builtin_files[] = {')
for i,n in enumerate(files):out.append('{"%s",builtin_%d,sizeof(builtin_%d),%d,%d},'%(n,i,i,1 if n in ('UNZIP','ZIP','EXIT') else 0,51810 if n=='UNZIP' else (int.from_bytes((root/'util/ZIP').read_bytes()[-4:],'big') if n=='ZIP' else (128 if n=='EXIT' else 0))))
out.append('};\n#define BUILTIN_COUNT (sizeof(builtin_files)/sizeof(builtin_files[0]))')
(root/'src/builtin_files.h').write_text('\n'.join(out)+'\n')

/* QL: * If bv_sing is clear: */
/* QL: * d0 -  o- 0 */
/* QL: * d1 -  o- bv_lengt (applies to prior line, zero if a4=pfbas). msw preserved. */
/* QL: * d2 -  o- bv_pfp */
/* QL: * d4 -ip - line number to go to */
/* QL: * a4 -i o- token within a line / found line length change or end of program */
/* QL: * ccr-  o- zero if a4<d2, otherwise a stop is set up and ccr is positive */
/* QL: ib_golin */
ib_golin:
/* QL:         tst.b   bv_sing(a6)     is this a command line other than goto? */
    tst.b bv_sing(a6)
/* QL:         beq.s   getlf */
    beq.s getlf
/* QL:         move.l  bv_tkbas(a6),a4 yes, so go to token base and return ok */
    move.l bv_tkbas(a6),a4
/* QL: ok_rts */
ok_rts:
/* QL:         moveq   #0,d0 */
    moveq #0,d0
/* QL:         rts */
    rts 
/* QL: findlf */
findlf:
/* QL:         bsr.s   ib_nxtk         get next token */
    bsr.s ib_nxtk
/* QL: getlf */
getlf:
/* QL:         cmp.w   #w.eol,0(a6,a4.l) are we at end of line? */
    cmp.w #w.eol,0(a6,a4.l)
/* QL:         bne.s   findlf          not yet, so keep looking */
    bne.s findlf
/* QL:         addq.l  #2,a4           space over lf */
    addq.l #2,a4
/* QL:         move.w  bv_lengt(a6),d1 pick up this line length */
    move.w bv_lengt(a6),d1
/* QL:         bsr.s   glin1           postion to requested line */
    bsr.s glin1
/* QL:         subq.w  #2,d1           left as +2 by routine */
    subq.w #2,d1
/* QL:         move.w  d1,bv_lengt(a6) store the prior line length */
    move.w d1,bv_lengt(a6)
/* QL:         cmp.l   a4,d2 */
    cmp.l a4,d2
/* QL:         bge.s   ok_rts */
    bge.s ok_rts
/* QL:         jmp     ib_steof(pc)    returns ccr for > 0 */
    jmp ib_steof(pc)
/* QL: * Moves a4 to point at next token in program file, or token list. */
/* QL: * This now ignores the top 3 bits of a token, as a token should only ever be */
/* QL: * one of $8x or $fx, with $8f currently undefined, so far! */
/* QL: * d0 -  o- 1st byte of next token */
/* QL: * d1 -  o- 1st word of next token */
/* QL: * a4 -i o- offset to tokenised code, moved across current token to next token */
/* QL: ib_nxtk */
ib_nxtk:
/* QL:         moveq   #31,d1          lose all but 5 lsb's of token */
    moveq #31,d1
/* QL:         and.b   0(a6,a4.l),d1   get token type */
    and.b 0(a6,a4.l),d1
/* QL:         move.b  toktab(pc,d1.w),d1 get no of bytes token comprises */
    move.b toktab(pc,d1.w),d1
/* QL:         bpl.s   add_tok         strings are different */
    bpl.s add_tok
/* QL:         neg.b   d1              no of bytes to add to no of chars */
    neg.b d1
/* QL:         add.w   2(a6,a4.l),d1   add no of chars */
    add.w 2(a6,a4.l),d1
/* QL:         bclr    #0,d1           make it even */
    bclr #0,d1
/* QL: add_tok */
add_tok:
/* QL:         add.l   d1,a4           move pointer along correct number of bytes */
    add.l d1,a4
/* QL:         move.w  0(a6,a4.l),d1   next token (word) */
    move.w 0(a6,a4.l),d1
/* QL:         move.l  d1,d0 */
    move.l d1,d0
/* QL:         lsr.w   #8,d0           next token (byte) */
    lsr.w #8,d0
/* QL:         rts */
    rts 
/* QL: toktab  dc.b    2,2,4,4,2,2,2,4,4,2,4,-5,-5,4,2,2 $80..$8f */
toktab:
dc_anchor_1062:

/* QL:         sf      sv_mdsta-sv_mddid-1(a5,d3.w) clear service request */
    sf ((sv_mdsta-sv_mddid)-1)(a5,d3.w)
/* QL:         move.b  -1(a5,d3.w),d3  get drive id*4 */
    move.b (-1)(a5,d3.w),d3
/* QL:         move.l  sv_fsdef-sv_mddid(a5,d3.w),a5 ...hence address of definition */
    move.l (sv_fsdef-sv_mddid)(a5,d3.w),a5
/* QL:         lsl.b   #4-2,d3         drive id * 16 */
    lsl.b #(4-2),d3
/* QL:         addq.b  #1<<bt..file,d3 + compare for file blocks */
    addq.b #(1<<bt..file),d3
/* QL:         movem.l d0-d3/a4-a5,-(sp) set up stack frame (d0-d2 & d3.msw = buff) */
    movem.l d0-d3/a4-a5,-(sp)
/* QL:         move.l  sp,a1           and point to it */
    move.l sp,a1
/* QL:         jsr     md_serve(pc) */
    jsr md_serve(pc)
/* QL:         add.w   #6*4,sp         remove sector, drive id, a4 and a5 from stack */
    add.w #(6*4),sp
/* QL: no_op */
no_op:
/* QL:         moveq   #-1-pc.maskg-pc.intrg,d7 */
    moveq #(((-1)-pc.maskg)-pc.intrg),d7
/* QL:         and.b   sv_pcint(a6),d7 temporarily mask gap interrupt */
    and.b sv_pcint(a6),d7
/* QL:         addq.b  #pc.intrg,d7    clear this interrupt */
    addq.b #pc.intrg,d7
/* QL:         move.b  d7,pc_intr-pc_mctrl(a3) */
    move.b d7,(pc_intr-pc_mctrl)(a3)
/* QL:         clr.b   d7              next reset the gap mask to normal */
    clr.b d7
/* QL:         bra.s   clearint        generate an interrupt if gap is already there */
    bra.s clearint
/* QL: ss_intrd */
ss_intrd:
/* QL: * Non-redirected traps come here... maybe we can get away with just this. */
/* QL: ss_int2 */
ss_int2:
/* QL:         movem.l regsone,-(sp) */
    movem.l d7/a5-a6,-(sp)
/* QL:         move.l  a7,d7 */
    move.l a7,d7
/* QL:         and.w   #$8000,d7 */
    and.w #0x8000,d7
/* QL:         move.l  d7,a6           do not assume there is only one screen */
    move.l d7,a6
/* QL:         movem.l regstwo,-(sp) */
    movem.l d0-d6/a0-a4,-(sp)
/* QL:         lea     pc_mctrl,a3 */
    lea pc_mctrl,a3
/* QL:         assert  pc_mctrl,pc_intr-1 */
/* original assertion: pc_mctrl,pc_intr-1 */
/* QL:         move.w  (a3),d7         fetch the interrupt register to lsb (tigeftig) */
    move.w (a3),d7
/* QL:         assert  1<<4,pc.intre,pc.intrf<<1 */
/* original assertion: 1<<4,pc.intre,pc.intrf<<1 */
/* QL:         lsl.b   #4,d7           check for external or frame interrupts */
    lsl.b #4,d7
/* QL:         bcs.s   exint */
    bcs.s exint
/* QL:         bmi.s   frint */
    bmi.s frint
/* QL:         moveq   #0,d3           no missing polls is common-ish */
    moveq #0,d3
/* QL:         assert  1<<2,pc.intrt,pc.intri<<1 */
/* original assertion: 1<<2,pc.intrt,pc.intri<<1 */
/* QL:         lsl.b   #2,d7           check for transmit, interface & gap interrupts */
    lsl.b #2,d7
/* QL:         bcs.s   txint */
    bcs.s txint
/* QL:         bmi.s   inint */
    bmi.s inint
/* QL:         bne.s   gpint */
    bne.s gpint
/* QL:         bra.s   nonred          no bits set! used for non-redirected traps! */
    bra.s nonred
/* QL: exint */
exint:
/* QL:         moveq   #sv_i2lst-sv_i2lst,d4 set offset of int 2 list from int 2 list */
    moveq #(sv_i2lst-sv_i2lst),d4
/* QL:         jsr     ss_tlist(pc)    do all external interrupt tasks */
    jsr ss_tlist(pc)
/* QL:         moveq   #pc.intre,d7    clear external */
    moveq #pc.intre,d7
/* QL: clearint */
clearint:
/* QL:         or.b    sv_pcint(a6),d7 get current interrupt mask */
    or.b sv_pcint(a6),d7
/* QL:         move.b  d7,pc_intr */
    move.b d7,pc_intr
/* QL:         movem.l (sp)+,regstwo */
    movem.l (sp)+,d0-d6/a0-a4
/* QL: one_rte */
one_rte:
/* QL:         movem.l (sp)+,regsone */
    movem.l (sp)+,d7/a5-a6
/* QL:         rte */
    rte 
/* QL: ss_noer */
ss_noer:
/* QL:         moveq   #0,d0           no error */
    moveq #0,d0
/* QL: ss_rte */
ss_rte:
/* QL:         tst.w   sv_pollm(a6)    check for missing polls */
    tst.w sv_pollm(a6)
/* QL:         beq.s   one_rte         none - return now */
    beq.s one_rte
/* QL: is_sup */
is_sup:
/* QL:         moveq   #1<<5,d7 */
    moveq #(1<<5),d7
/* QL:         and.b   12(sp),d7       check if called from supervisor state */
    and.b 12(sp),d7
/* QL:         bne.s   one_rte         yes - direct return */
    bne.s one_rte
/* QL:         jmp     ss_reshd(pc)    reenter scheduler */
    jmp ss_reshd(pc)
/* QL: * Serial port transmit interrupt */
/* QL: txint */
txint:
/* QL: *       moveq   #0,d3           no missing polls already set */
/* QL:         st      d4              not called from scheduler */
    st d4
/* QL:         jsr     ip_txqo(pc)     send any rs232 */
    jsr ip_txqo(pc)
/* QL:         moveq   #pc.intrt,d7    clear this interrupt */
    moveq #pc.intrt,d7
/* QL:         bra.s   clearint */
    bra.s clearint
/* QL: * Interface interrupt, serial data available */
/* QL: inint */
inint:
/* QL: *       moveq   #0,d3           no missing polls alredy set */
/* QL:         jsr     ip_ipcr(pc)     read status and handle anything it says */
    jsr ip_ipcr(pc)
/* QL:         moveq   #pc.intri,d7    clear this interrupt */
    moveq #pc.intri,d7
/* QL:         bra.s   clearint */
    bra.s clearint
/* QL: * Frame interrupt, 50Hz (or 60Hz USA) */
/* QL: frint */
frint:
/* QL:         addq.w  #1,sv_pollm(a6) increment count of poll interupts */
    addq.w #1,sv_pollm(a6)
/* QL:         bvc.s   do_poll         ... ok? */
    bvc.s do_poll
/* QL:         subq.w  #1,sv_pollm(a6) ... no reset it (slightly unsafe!) */
    subq.w #1,sv_pollm(a6)
/* QL: do_poll */
do_poll:
/* QL:         moveq   #1,d3           just one poll since last time!! */
    moveq #1,d3
/* QL:         moveq   #sv_plist-sv_i2lst,d4 set offset of poll list from int 2 list */
    moveq #(sv_plist-sv_i2lst),d4
/* QL:         jsr     ss_tlist(pc)    scan the list */
    jsr ss_tlist(pc)
/* QL:         moveq   #pc.intrf,d7    set to clear frame interrupt */
    moveq #pc.intrf,d7
/* QL:         or.b    sv_pcint(a6),d7 fetch interrupt register value */
    or.b sv_pcint(a6),d7
/* QL:         move.b  d7,pc_intr      and clear it */
    move.b d7,pc_intr
/* QL: nonred */
nonred:
/* QL:         movem.l (sp)+,regstwo */
    movem.l (sp)+,d0-d6/a0-a4
/* QL:         bra.s   is_sup          go see if we were in supervisor mode */
    bra.s is_sup
/* QL:         end */

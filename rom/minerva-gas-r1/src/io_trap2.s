/* QL: fs_drivn ds.b   1       drive number */
.equ fs_drivn,20
/* QL:         ds.b    1 */
/* QL: fs_mname ds.w   1+10/2  length prefixed medium name */
.equ fs_mname,22
/* QL: fs_files ds.b   1       number of files open */
.equ fs_files,34
/* QL: * file system trap #3 codes */
/* QL: fs.check  equ    $40                check all pending operations */
.equ fs.check,0x40
/* QL: fs.flush  equ    $41                flush buffers */
.equ fs.flush,0x41
/* QL: fs.posab  equ    $42                position file pointer (absolute) */
.equ fs.posab,0x42
/* QL: fs.posre  equ    $43                position file pointer (relative) */
.equ fs.posre,0x43
/* QL: fs.mdinf  equ    $45                information about medium */
.equ fs.mdinf,0x45
/* QL: fs.heads  equ    $46                set file header */
.equ fs.heads,0x46
/* QL: fs.headr  equ    $47                read file header */
.equ fs.headr,0x47
/* QL: fs.load   equ    $48                load file */
.equ fs.load,0x48
/* QL: fs.save   equ    $49                save file */
.equ fs.save,0x49
/* QL: fs.renam  equ    $4a                rename file */
.equ fs.renam,0x4a
/* QL: fs.trunc  equ    $4b                truncate file */
.equ fs.trunc,0x4b
/* QL:         list */
/* QL:         include 'win1_m_inc_assert' */
/* QL: * Improved assert - accepts comparison operators */
/* QL:         nolist */
/* QL: assert macro */
/* QL:         list */
/* QL:         section io_trap2 */
.section io_trap2,"ax"
/* QL: io_trap2 */
io_trap2:
/* QL:         movem.l d7/a5-a6,-(sp)  save standard registers */
    movem.l d7/a5-a6,-(sp)
/* QL:         move.l  a7,d7 */
    move.l a7,d7
/* QL:         and.w   #$8000,d7 */
    and.w #0x8000,d7
/* QL:         move.l  d7,a6           do not assume there is only one screen */
    move.l d7,a6
/* QL:         moveq   #127,d7         ensure trap is positive byte only */
    moveq #127,d7
/* QL:         and.l   d7,d0 */
    and.l d7,d0
/* QL:         move.l  sv_jbpnt(a6),a5 get current job pointer */
    move.l sv_jbpnt(a6),a5
/* QL:         move.l  (a5),a5         ... thus base of job */
    move.l (a5),a5
/* QL:         bclr    d7,jb_rela6(a5) clear and test relative addressing flag */
    bclr d7,jb_rela6(a5)
/* QL:         beq.s   trap_sel */
    beq.s trap_sel
/* QL:         add.l   2*4(sp),a0      add a6 offset to address of name */
    add.l (2*4)(sp),a0
/* QL: trap_sel */
trap_sel:
/* QL: *       move.l  sp,a5           set trap level pointer to stack */
/* QL:         subq.b  #io.open,d0 */
    subq.b #io.open,d0
/* QL:         beq.s   io_open */
    beq.s io_open
/* QL:         assert  1,io.close-io.open,io.formt-io.close */
/* original assertion: 1,io.close-io.open,io.formt-io.close */
/* QL:         subq.b  #io.formt-io.open,d0 */
.word 20736|((((io.formt-io.open))&7)<<9)
/* QL:         bcs.s   io_close */
    bcs.s io_close
/* QL:         beq.s   io_formt */
    beq.s io_formt
/* QL:         subq.b  #io.delet-io.formt,d0 */
.word 20736|((((io.delet-io.formt))&7)<<9)
/* QL:         beq.s   io_delet */
    beq.s io_delet
/* QL:         moveq   #err.bp,d0      oh dear! */
    moveq #err.bp,d0
/* QL:         bra.s   ssrte */
    bra.s ssrte
/* QL: * d0 -  o- error code */
/* QL: * d1 -  o- drive number (msw) and number of good sectors (lsw) */
/* QL: * d2 -  o- total number of sectors */
/* QL: * a0 -i  - pointer to medium name */
/* QL: * a1 destroyed, though it needn't be */
/* QL: fmt_reg reg     d3-d6/a2-a4 */
/* QL: io_formt */
io_formt:
/* QL:         movem.l fmt_reg,-(sp) */
    movem.l d3-d6/a2-a4,-(sp)
/* QL:         jsr     io_fdriv(pc)    go look up a device driver for this name */
    jsr io_fdriv(pc)
/* QL:         blt.s   fmtexit         driver not found */
    blt.s fmtexit
/* QL:         bne.s   fmtok           no physdef is ok */
    bne.s fmtok
/* QL:         tst.b   fs_files(a1)    any files open on the medium? */
    tst.b fs_files(a1)
/* QL:         beq.s   fmtok           no - fine */
    beq.s fmtok
/* QL:         move.l  sv_chtop(a6),a1 get extension address */
    move.l sv_chtop(a6),a1
/* QL:         tst.b   sx_toe(a1)      are we to treate this as an error? */
    tst.b sx_toe(a1)
/* QL:         bmi.s   fmtok           nope, allow silly bug in dp's conqueror */
    bmi.s fmtok
/* QL:         moveq   #err.iu,d0      surely can't do it with files open? (added lwr) */
    moveq #err.iu,d0
/* QL:         bra.s   fmtexit */
    bra.s fmtexit
/* QL: fmtok */
fmtok:
/* QL:         move.l  a0,a1           oh me, oh my. why does is have to be in both? */
    move.l a0,a1
/* QL: *       movem.l (sp),d3-d4      should we really have to do this? (lwr) */
/* QL:         lea     -sv_lio(a2),a3  set up base driver definition block */
    lea (-sv_lio)(a2),a3
/* QL:         move.l  ch_formt(a2),a4 */
    move.l ch_formt(a2),a4
/* QL:         jsr     (a4) */
    jsr (a4)
/* QL: fmtexit */
fmtexit:
/* QL:         movem.l (sp)+,fmt_reg */
    movem.l (sp)+,d3-d6/a2-a4
/* QL:         bra.s   ssrte */
    bra.s ssrte
/* QL: * d0 -  o- error code (well... close calls should never say they fail!) */
/* QL: * a0 -i  - channel id */
/* QL: * a1 destroyed (though mt_close could save it...) */
/* QL: io_close */
io_close:
/* QL:         jsr     io_chanx(pc)    check that channel exists (a0->a5, chan->a0) */
    jsr io_chanx(pc)
/* QL:         jsr     mt_close(pc)    go do the closure */
    jsr mt_close(pc)
/* QL: ssrte */
ssrte:
/* QL:         jmp     ss_rte(pc) */
    jmp ss_rte(pc)
/* QL: * d0 -  o- error code */
/* QL: * d1 -  o- current job id */
/* QL: * a0 -i  - pointer to word length prefixed device/file name */
/* QL: * d3/a1 destroyed */
/* QL: io_delet */
io_delet:
/* QL:         move.l  a0,a1           save address of name */
    move.l a0,a1
/* QL:         jsr     ss_joby(pc)     get own job id in d1, address in a0 */
    jsr ss_joby(pc)
/* QL:         exg     a0,a1           address of job goes to a1 */
    exg a1,a0
/* QL:         st      d3              d3 key for delete */
    st d3
/* QL:         jsr     io_fopen(pc)    delete file */
    jsr io_fopen(pc)
/* QL:         bra.s   ssrte */
    bra.s ssrte
/* QL: * d0 -  o- error code */
/* QL: * d1 -i o- job id (real one on output) */
/* QL: * d3 -ip - access code */
/* QL: * a0 -i o- filename / cahnnelid */
/* QL: * a1 destroyed */
/* QL: op_save reg     a0/a2-a4 */
/* QL: opn_reg reg     d1-d6/a1-a3/a6  open allowed to destroy all regs, as per doc! */
/* QL: io_open */
io_open:
/* QL:         move.l  a0,a1           save address of name */
    move.l a0,a1
/* QL:         jsr     ss_jobx(pc)     check if job exists (no return on failure) */
    jsr ss_jobx(pc)
/* QL:         exg     a0,a1           address of job goes to a1 */
    exg a1,a0
/* QL:         movem.l op_save,-(sp)   save a few registers to be used here */
    movem.l a0/a2-a4,-(sp)
/* QL:         moveq   #err.no,d0      out of room / select sys_tag table */
    moveq #err.no,d0
/* QL:         lea     sv_chbas(a6),a4 this is the table to look in */
    lea sv_chbas(a6),a4
/* QL:         jsr     ss_tag(pc)      look for new channel slot */
    jsr ss_tag(pc)
/* QL:         bmi.s   exit_op         couldn't find a new slot */
    bmi.s exit_op
/* QL:         move.l  d0,(sp)         set new channel id (maybe) */
    move.l d0,(sp)
/* QL:         lea     sv_drlst(a6),a2 get address of first device driver */
    lea sv_drlst(a6),a2
/* QL: chk_next */
chk_next:
/* QL:         move.l  (a2),a2         try next driver */
    move.l (a2),a2
/* QL:         move.l  a2,d0 */
    move.l a2,d0
/* QL:         beq.s   chk_file */
    beq.s chk_file
/* QL: chk_loop */
chk_loop:
/* QL:         movem.l opn_reg,-(sp) */
    movem.l d1-d6/a1-a3/a6,-(sp)
/* QL:         lea     -sv_lio(a2),a3  set base of driver definition block */
    lea (-sv_lio)(a2),a3
/* QL:         move.l  ch_open(a2),a4  indirect */
    move.l ch_open(a2),a4
/* QL:         jsr     (a4)            try opening this device type */
    jsr (a4)
/* QL:         movem.l (sp)+,opn_reg */
    movem.l (sp)+,d1-d6/a1-a3/a6
/* QL:         tst.l   d0 */
    tst.l d0
/* QL:         beq.s   open            was channel opened */
    beq.s open
/* QL:         cmp.w   #err.nf,d0      check if error was 'not found' */
    cmp.w #err.nf,d0
/* QL:         beq.s   chk_next        that was ok */
    beq.s chk_next
/* QL: exit_op */
exit_op:
/* QL:         movem.l (sp)+,op_save */
    movem.l (sp)+,a0/a2-a4
/* QL:         bra.s   ssrte */
    bra.s ssrte
/* QL: * Finally try the file system */
/* QL: chk_file */
chk_file:
/* QL:         moveq   #err.bp,d0 */
    moveq #err.bp,d0
/* QL:         cmp.b   #io.dir,d3      check access key */
    cmp.b #(io.dir&255),d3
/* QL:         bhi.s   exit_op */
    bhi.s exit_op
/* QL:         jsr     io_fopen(pc) */
    jsr io_fopen(pc)
/* QL:         bne.s   exit_op */
    bne.s exit_op
/* QL: open */
open:
/* QL:         move.l  a0,(a3)         set address of channel definition block */
    move.l a0,(a3)
/* QL:         addq.l  #4,a0           length of block is in header already */
    addq.l #4,a0
/* QL:         move.l  a2,(a0)+        put address of device driver in */
    move.l a2,(a0)+
/* QL:         move.l  d1,(a0)+        put job id in */
    move.l d1,(a0)+
/* QL:         move.l  a3,(a0)+        address of release flag */
    move.l a3,(a0)+
/* QL:         move.w  (sp),(a0)+      put tag in */
    move.w (sp),(a0)+
/* QL:         clr.w   (a0)+           status ok, no pending action */
    clr.w (a0)+
/* QL:         clr.l   (a0)+           no job waiting */
    clr.l (a0)+
/* QL:         bra.s   exit_op */
    bra.s exit_op
/* QL:         end */

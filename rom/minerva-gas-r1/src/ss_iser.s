/* QL: wait */
wait:
/* QL:         move.l  d0,-(sp)        save operation */
    move.l d0,-(sp)
/* QL: full */
full:
/* QL:         btst    #pc..txfl,pc_ipcrd */
    btst #pc..txfl,pc_ipcrd
/* QL:         bne.s   full            wait until transmit buffer is empty */
    bne.s full
/* QL:         moveq   #12-1,d0        start bit comes 1/2 bit later, 8 data + 2 stop */
    moveq #(12-1),d0
/* QL: high */
high:
/* QL:         tst.b   pc_intr */
    tst.b pc_intr
/* QL:         bmi.s   high             (actually always low when buffer empties) */
    bmi.s high
/* QL: low */
low:
/* QL:         tst.b   pc_intr */
    tst.b pc_intr
/* QL:         bpl.s   low */
    bpl.s low
/* QL:         dbra    d0,high */
    dbra d0,high
/* QL:         move.l  (sp)+,d0        restore operation */
    move.l (sp)+,d0
/* QL: nowait */

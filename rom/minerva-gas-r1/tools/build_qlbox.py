#!/usr/bin/env python3
"""Build a distinct QLBox ROM from the byte-exact Minerva source assembly.

Only three instruction ranges are replaced, each at identical width. The
standard extension header supplies SHUTDOWN and installs the host device;
Minerva continues to own all traps, scheduling, channels and BASIC execution.
"""
import os, pathlib, subprocess, json, re
R=pathlib.Path(__file__).resolve().parents[1];os.chdir(R)
B=R/'build';prefix=os.environ.get('CROSS','m68k-elf-')
subprocess.run([os.environ.get('PYTHON','python3'),'tools/build.py'],check=True)
s=(B/'minerva.s').read_text()
patches=[
 ('channel identity','M18_open:\n    move.l a0,(a3)\n    addq.l #4,a0\n    move.l a2,(a0)+',
  'M18_open:\n    jsr host_channel_setup:l'),
 ('delete dispatch','M18_io_delet:\n    move.l a0,a1\n    jsr ss_joby(pc)',
  'M18_io_delet:\n    jmp host_delete_entry:l'),
 ('CLI boot','    moveq #0,d4\n    bsr.s M139_mov_wind\n    bsr.s M139_mov_next\n    bsr.s M139_mov_next',
  '    jsr host_start:l\n    nop'),
]
# Original comments sit between statements: retain them in the stock source,
# remove them from this generated build input to make guarded replacements clear.
s=re.sub(r'/\*.*?\*/','',s,flags=re.S)
s='\n'.join(line for line in s.splitlines() if line.strip())+'\n'
for name,old,new in patches:
 if s.count(old)!=1:raise SystemExit('Patch anchor changed: '+name)
 s=s.replace(old,new)
s+='\n.include "qlbox/extension.s"\n'
(B/'minerva-qlbox.s').write_text(s)
def run(*a):subprocess.run(a,check=True)
run(prefix+'as','-m68000','--register-prefix-optional','--bitwise-or','-I',str(R),'-o',str(B/'minerva-qlbox.o'),str(B/'minerva-qlbox.s'))
run(prefix+'ld','-Ttext=0','-e','0x410','-Map',str(B/'minerva-qlbox.map'),'-o',str(B/'minerva-qlbox.elf'),str(B/'minerva-qlbox.o'))
run(prefix+'objcopy','-O','binary',str(B/'minerva-qlbox.elf'),str(B/'minerva-qlbox.rom'))
with (B/'minerva-qlbox.symbols').open('w') as f:subprocess.run([prefix+'nm','-n',str(B/'minerva-qlbox.elf')],stdout=f,check=True)
def symbols(path):
 return {p[2]:int(p[0],16) for line in path.read_text().splitlines() if len(p:=line.split())==3}
stock=symbols(B/'minerva.symbols');mod=symbols(B/'minerva-qlbox.symbols')
assert all(mod[k]==v for k,v in stock.items() if k not in ('_end','_edata','__bss_start')),'Original symbols moved'
a=(B/'minerva.rom').read_bytes();b=(B/'minerva-qlbox.rom').read_bytes();assert len(b)==65536
allowed=set(range(stock['M18_open'],stock['M18_open']+6))|set(range(stock['M18_io_delet'],stock['M18_io_delet']+6))|set(range(stock['M139_getboot']-10,stock['M139_getboot']-2))
changed={i for i,(x,y) in enumerate(zip(a,b)) if x!=y}
assert changed<=allowed,sorted(changed-allowed)
h=2166136261
for v in b:h=((h^v)*16777619)&0xffffffff
header=R.parent.parent/'src/minerva_profile.h'
header.write_text('/* Generated by rom/minerva-gas-r1/tools/build_qlbox.py. */\n#define QL_MINERVA_HOST_HASH 0x%08xu\n'%h)
print('QLBox Minerva: %d changed core bytes; all original symbols retained; FNV %08x'%(len(changed),h))
